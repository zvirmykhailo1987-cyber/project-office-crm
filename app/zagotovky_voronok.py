def stadiyi_zagotovky(kod: str) -> list[dict]:
    """Стадії заготовки у вигляді, готовому для створення `Stage`.

    Ймовірність — рівномірний крок по робочих стадіях. Термінальні отримують
    100 % для виграшу і 0 % для решти. Це єдина «формула» тут, і вона навмисно
    тупа: підганяти ймовірності під чужий процес — вигадувати досвід.
    """
    z = ZAGOTOVKY.get(kod)
    if not z:
        return []
    robochi = [s for s in z["stadiyi"] if not s[4]]
    krok = 90 // max(1, len(robochi))
    out, i = [], 0
    for kodst, nazva, tsil, gate, rez in z["stadiyi"]:
        if rez:
            ymov = 100 if rez == "vygrash" else 0
        else:
            i += 1
            ymov = min(90, krok * i)
        out.append(dict(code=kodst, title=nazva, goal=tsil, gate_criteria=gate,
                        rezultat=rez, default_probability=ymov,
                        required_doc_kinds="", key_docs="", color="#64748b"))
    return out
